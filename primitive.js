// tipos primitivos de dados

// string
let saudacao = 'hello, world!'
console.log(saudacao)
console.log(typeof saudacao, 'saudacao')

// number
let age = 27
console.log(age)
console.log(typeof age, 'age')

let price = 19.99
console.log(price)
console.log(typeof price, 'price')

// boolean
let ligado = true
console.log(ligado)
console.log(typeof ligado, 'ligado')

let desligado = false
console.log(desligado)
console.log(typeof desligado, 'desligado')

// null
let resultado = null
console.log(resultado)
console.log(typeof resultado, 'resultado')

// undefined
let status
console.log(status)
console.log(typeof status, 'status')
